const router = require('express').Router();
const order = require('../controllers/orderController');
const { protect } = require('../middleware/authMiddleware');
const { adminOnly, requirePermission } = require('../middleware/adminMiddleware');
router.post('/', protect, order.createOrder);
router.post('/cod', protect, order.createCodOrder);
router.get('/', protect, adminOnly, requirePermission('manage_orders'), order.adminOrders);
router.get('/:id/receipt', protect, order.receipt);
router.put('/:id/status', protect, adminOnly, requirePermission('manage_orders'), order.updateOrderStatus);
router.put('/:id/payment-status', protect, adminOnly, requirePermission('manage_orders'), order.updatePaymentStatus);
router.delete('/:id', protect, adminOnly, requirePermission('manage_orders'), order.deleteOrder);
router.post('/:id/cancel', protect, order.cancelOrder);
router.post('/:id/refund-retry', protect, adminOnly, requirePermission('refund_payments'), order.retryCancellationRefund);
router.get('/my-orders', protect, order.myOrders);
router.get('/admin/all', protect, adminOnly, requirePermission('manage_orders'), order.adminOrders);
router.get('/admin/:id', protect, adminOnly, requirePermission('manage_orders'), order.getOrder);
router.get('/admin/:id/receipt', protect, adminOnly, requirePermission('manage_orders'), order.receipt);
router.put('/admin/:id/status', protect, adminOnly, requirePermission('manage_orders'), order.updateOrderStatus);
router.put('/admin/:id/payment-status', protect, adminOnly, requirePermission('manage_orders'), order.updatePaymentStatus);
router.get('/:id', protect, order.getOrder);
module.exports = router;
